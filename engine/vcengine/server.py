@app.post("/engine/start")
def start():
    if _preview_lock.locked():
        raise HTTPException(409, "Дождитесь завершения подготовки примера")
    if not _inference_lock.acquire(blocking=False):
        raise HTTPException(409, "Дождитесь завершения подготовки примера")
    try:
        engine.start()
    finally:
        _inference_lock.release()
    save_settings()
    return engine.status()


