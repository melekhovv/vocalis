@app.websocket("/ws")
async def ws(sock: WebSocket):
    tok = sock.query_params.get("token")
    if not tok or not secrets.compare_digest(tok, TOKEN):
        await sock.close(code=4401)
        return
    await sock.accept()
    last_rev = -1
    try:
        while True:
            st = full_status()
            msg = {"type": "status", **st}
            if st["rev"] != last_rev:
                msg["voices"] = models.list_voices()
                last_rev = st["rev"]
            elif any(v.get("status") == "downloading" for v in models.list_voices()) or st["baseAssets"]["job"]:
                msg["voices"] = models.list_voices()
            await sock.send_text(json.dumps(msg, ensure_ascii=False))
            await asyncio.sleep(0.1)
    except (WebSocketDisconnect, RuntimeError):
        pass


# ------------------------------------------------------------------ entry
def _watch_parent(ppid):
    """Exit when the desktop shell dies so streams never outlive the UI."""
    import psutil

    while True:
        if not psutil.pid_exists(ppid):
            engine.stop()
            os._exit(0)
        time.sleep(1)


@app.post("/shutdown")
def shutdown():
    engine.stop()
    threading.Timer(0.2, lambda: os._exit(0)).start()
    return {"ok": True}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=0)
    ap.add_argument("--parent-pid", type=int, default=0)
    args = ap.parse_args()
    if args.parent_pid:
        threading.Thread(target=_watch_parent, args=(args.parent_pid,), daemon=True).start()

    import socket

    sock = socket.socket()
    sock.bind(("127.0.0.1", args.port))
    port = sock.getsockname()[1]
    print(f"VOCALIS_READY {port}", flush=True)
    if not os.environ.get("VOCALIS_TOKEN"):
        print(f"VOCALIS_TOKEN {TOKEN}", flush=True)
    config = uvicorn.Config(app, log_level="warning", access_log=False)
    server = uvicorn.Server(config)
    try:
        server.run(sockets=[sock])
    finally:
        engine.stop()


if __name__ == "__main__":
    sys.exit(main())
