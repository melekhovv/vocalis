@app.post("/engine/compute")
def compute(body: dict):
    dev = body.get("device", "auto")
    if dev not in ("auto", "cpu"):
        raise HTTPException(400, "device должен быть auto или cpu")
    if engine.state == "loading":
        raise HTTPException(409, "Дождитесь загрузки модели перед сменой устройства вычислений")
    if engine.compute == dev:
        return engine.status()
    engine.compute = dev
    if engine.state == "running":
        engine.restart()
    save_settings()
    return engine.status()


# ------------------------------------------------------------------ preview
_preview_lock = asyncio.Lock()
_inference_lock = threading.Lock()


def demo_clip():
    path = PREVIEW_DIR / "user-input.wav"
    if not path.is_file():
        raise HTTPException(400, "Выберите свой WAV-файл для прослушивания в библиотеке")
    clip, _ = sf.read(path, dtype="float32")
    return clip


@app.get("/preview/input")
def preview_input_info():
    return {"ready": (PREVIEW_DIR / "user-input.wav").is_file()}


@app.post("/preview/input")
async def preview_input(body: dict):
    from pathlib import Path
    import soxr
    if _preview_lock.locked():
        raise HTTPException(409, "Дождитесь подготовки текущего примера")
    path = Path(required(body, "path"))
    if path.suffix.lower() != ".wav" or not path.is_file():
        raise HTTPException(400, "Выберите существующий WAV-файл")
    try:
        info = sf.info(path)
        if not 0 < info.duration <= 30 or not 8000 <= info.samplerate <= 192000 or not 1 <= info.channels <= 8:
            raise ValueError("Нужен WAV длительностью до 30 секунд, 8–192 кГц, до 8 каналов")
        clip, sr = sf.read(path, dtype="float32")
        if not np.isfinite(clip).all():
            raise ValueError("Аудио содержит некорректные значения")
        if clip.ndim > 1:
            clip = clip.mean(axis=1)
        if sr != audio_mod.SR:
            clip = soxr.resample(clip, sr, audio_mod.SR)
        sf.write(PREVIEW_DIR / "user-input.wav", clip, audio_mod.SR)
    except (RuntimeError, ValueError) as e:
        raise HTTPException(400, f"Не удалось прочитать аудио: {e}") from e
    return {"ready": True}


@app.post("/preview/convert")
async def preview_convert(body: dict):
    vid = body.get("voiceId")
    voice = next((v for v in models.list_voices() if v["id"] == vid), None)
    if voice is None:
        raise HTTPException(404, "Голос отсутствует в библиотеке")
    async with _preview_lock:
        if not _inference_lock.acquire(blocking=False):
            raise HTTPException(409, "Дождитесь завершения текущей операции")
        try:
            if engine.state in ("running", "loading"):
                raise HTTPException(400, "Остановите преобразование для подготовки примера")
            if not models.base_assets_status()["ready"]:
                raise HTTPException(400, "Базовые модели ещё не загружены")
            models.voice_paths(vid)
            clip = demo_clip()
            params = {"pitch": voice.get("suggestedPitch", 0), "index_rate": 0.75, "protect": 0.33}
            params.update({k: v for k, v in (voice.get("recommendedParams") or {}).items() if k in ("index_rate", "protect")})
            t0 = time.perf_counter()
            out = await asyncio.to_thread(audio_mod.convert_clip, models, vid, clip, params, "quality", engine.compute)
            name = f"demo-{vid}.wav"
            sf.write(PREVIEW_DIR / name, out, audio_mod.SR)
            return {"url": f"/preview/audio/{name}", "seconds": round(time.perf_counter() - t0, 2)}
        finally:
            _inference_lock.release()


@app.get("/preview/audio/{name}")
def preview_audio(name: str):
    voices = models.list_voices()
    allowed = {f"demo-{v['id']}.wav" for v in voices}
    if name not in allowed:
        raise HTTPException(404)
    p = PREVIEW_DIR / name
    if not p.is_file():
        raise HTTPException(404)
    return FileResponse(p, media_type="audio/wav", headers={"Cache-Control": "no-store"})


# ------------------------------------------------------------------ websocket
@app.websocket("/ws")
async def ws(sock: WebSocket):
    tok = sock.query_params.get("token")
    if not tok or not secrets.compare_digest(tok, TOKEN):
        await sock.close(code=4401)
        return
    await sock.accept()
    last_rev = -1
    try:
        while True:
            st = full_status()
            msg = {"type": "status", **st}
            if st["rev"] != last_rev:
                msg["voices"] = models.list_voices()
                last_rev = st["rev"]
            elif any(v.get("status") == "downloading" for v in models.list_voices()) or st["baseAssets"]["job"]:
                msg["voices"] = models.list_voices()
            await sock.send_text(json.dumps(msg, ensure_ascii=False))
            await asyncio.sleep(0.1)
    except (WebSocketDisconnect, RuntimeError):
        pass


# ------------------------------------------------------------------ entry
def _watch_parent(ppid):
    """Exit when the desktop shell dies so streams never outlive the UI."""
    import psutil

    while True:
        if not psutil.pid_exists(ppid):
            engine.stop()
            os._exit(0)
        time.sleep(1)


@app.post("/shutdown")
def shutdown():
    engine.stop()
    threading.Timer(0.2, lambda: os._exit(0)).start()
    return {"ok": True}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=0)
    ap.add_argument("--parent-pid", type=int, default=0)
    args = ap.parse_args()
    if args.parent_pid:
        threading.Thread(target=_watch_parent, args=(args.parent_pid,), daemon=True).start()

    import socket

    sock = socket.socket()
    sock.bind(("127.0.0.1", args.port))
    port = sock.getsockname()[1]
    print(f"VOCALIS_READY {port}", flush=True)
    if not os.environ.get("VOCALIS_TOKEN"):
        print(f"VOCALIS_TOKEN {TOKEN}", flush=True)
    config = uvicorn.Config(app, log_level="warning", access_log=False)
    server = uvicorn.Server(config)
    try:
        server.run(sockets=[sock])
    finally:
        engine.stop()


if __name__ == "__main__":
    sys.exit(main())
